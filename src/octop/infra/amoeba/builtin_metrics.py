# Metrics the MCP source must be able to serve (everything without a formula).
RAW_METRIC_KEYS: list[str] = [m.metric_key for m in BUILTIN_METRICS if not m.formula]

__all__ = [
    "BUILTIN_GROUP_LAYOUT",
    "BUILTIN_METRICS",
    "RAW_METRIC_KEYS",
    "ensure_builtin_metrics",
]


def ensure_builtin_metrics(repo: object) -> None:
    """Seed/refresh builtin metrics into the catalog (idempotent)."""
    from octop.infra.db.repos.amoeba import AmoebaRepo

    assert isinstance(repo, AmoebaRepo)
    repo.upsert_builtin_metrics(BUILTIN_METRICS)
