def _m(
    key: str,
    zh: str,
    en: str,
    *,
    unit: str = "",
    category: str = "hidden",
    formula: str = "",
    note_zh: str = "",
    note_en: str = "",
    format: str = "number",
    agg: str = "sum",
    color: str = "",
    sort: int = 0,
) -> AmoebaMetricRow:
    return AmoebaMetricRow(
        metric_key=key,
        name_zh=zh,
        name_en=en,
        unit=unit,
        category=category,
        formula=formula,
        note_zh=note_zh,
        note_en=note_en,
        format=format,
        agg=agg,
        color=color,
        sort=sort,
        enabled=True,
        builtin=True,
    )


