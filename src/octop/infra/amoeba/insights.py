"""Board narrative: leveled insight items (risk / warn / opp / info) with a
one-line lead summary, generated by the LLM with a rule-based fallback."""

from __future__ import annotations

import asyncio
import json
import logging
from typing import Any

from octop.i18n import tr
from octop.infra.utils.llm_text import strip_thinking

logger = logging.getLogger(__name__)

_LLM_TIMEOUT_SECONDS = 25.0
_MAX_ITEMS = 6
_MAX_LINE_LEN = 200
# Only cards from these groups feed the rule-based insights.
_RULE_GROUPS = ("core", "profit", "pay")

LEVELS = ("risk", "warn", "opp", "info")
_LEVEL_ORDER = {name: idx for idx, name in enumerate(LEVELS)}


def _fmt(value: Any) -> str:
    if value is None:
        return "-"
    if isinstance(value, float) and value == int(value):
        return str(int(value))
    return f"{value:.2f}".rstrip("0").rstrip(".")


def _metric_name(card: dict[str, Any], locale: str) -> str:
    name: str = card["name_zh"] if str(locale).startswith("zh") else card["name_en"]
    return name


def _card_level(card: dict[str, Any]) -> str:
    budget_pct = card.get("budget_pct")
    delta_pct = card.get("delta_pct")
    if budget_pct is not None:
        if budget_pct < 80:
            return "risk"
        if budget_pct < 100:
            return "warn"
        return "opp"
    if delta_pct is not None:
        if delta_pct < -10:
            return "risk"
        if delta_pct < 0:
            return "warn"
        return "opp"
    return "info"


def _rule_item(card: dict[str, Any], level: str, dim: str, locale: str) -> dict[str, Any] | None:
    name = _metric_name(card, locale)
    value = card.get("dims", {}).get(dim)
    budget_pct = card.get("budget_pct")
    delta_pct = card.get("delta_pct")
    unit = card.get("unit") or ""
    if budget_pct is not None and budget_pct < 100:
        title = tr("amoeba.insights.titles.behindBudget", locale, name=name)
        evidence = tr(
            "amoeba.insights.evidence.valueBudget",
            locale,
            value=_fmt(value),
            unit=unit,
            pct=_fmt(budget_pct),
        )
        action = tr("amoeba.insights.actions.push", locale)
    elif budget_pct is not None:
        title = tr("amoeba.insights.titles.aheadBudget", locale, name=name)
        evidence = tr(
            "amoeba.insights.evidence.valueBudget",
            locale,
            value=_fmt(value),
            unit=unit,
            pct=_fmt(budget_pct),
        )
        action = tr("amoeba.insights.actions.keep", locale)
    elif delta_pct is not None and delta_pct < 0:
        title = tr("amoeba.insights.titles.declining", locale, name=name)
        evidence = tr(
            "amoeba.insights.evidence.valueDelta",
            locale,
            value=_fmt(value),
            unit=unit,
            pct=_fmt(delta_pct),
        )
        action = tr("amoeba.insights.actions.watch", locale)
    elif delta_pct is not None:
        title = tr("amoeba.insights.titles.growing", locale, name=name)
        evidence = tr(
            "amoeba.insights.evidence.valueDelta",
            locale,
            value=_fmt(value),
            unit=unit,
            pct=_fmt(delta_pct),
        )
        action = tr("amoeba.insights.actions.keep", locale)
    else:
        return None
    return {
        "level": level,
        "title": title,
        "evidence": evidence,
        "action": action,
        "source": "rule",
    }


def rule_insights(overview: dict[str, Any], *, locale: str, org_name: str) -> list[dict[str, Any]]:
    """Deterministic leveled insights from budget attainment / deltas."""
    dim = overview.get("dim", "d")
    group_keys = {
        key
        for g in overview.get("groups", [])
        if g.get("category") in _RULE_GROUPS
        for key in g.get("metric_keys", [])
    }
    items: list[dict[str, Any]] = []
    for key in sorted(group_keys):
        card = overview.get("metrics", {}).get(key)
        if not card:
            continue
        item = _rule_item(card, _card_level(card), dim, locale)
        if item:
            items.append(item)
        if len(items) >= _MAX_ITEMS * 3:
            break
    if not items:
        return [
            {
                "level": "info",
                "title": tr("amoeba.insights.titles.noSignal", locale),
                "evidence": tr("amoeba.insights.evidence.noSignal", locale, org=org_name),
                "action": "",
                "source": "rule",
            }
        ]
    # Worst levels first (risk < warn < opp < info), keep the cap.
    items.sort(key=lambda i: _LEVEL_ORDER.get(i["level"], 99))
    return items[:_MAX_ITEMS]


def lead_line(overview: dict[str, Any], items: list[dict[str, Any]], *, locale: str) -> str:
    """One-sentence board verdict used as the page hero line."""
    dim = overview.get("dim", "d")
    metrics = overview.get("metrics", {})
    profit = metrics.get("profit")
    revenue = metrics.get("rev") or metrics.get("oil")
    if profit and profit.get("dims", {}).get(dim) is not None:
        trend = profit.get("delta_pct")
        # On the monthly dimension the profit card carries no budget; quote the
        # revenue attainment instead so the hero line never shows bare dashes.
        budget = profit.get("budget_pct")
        if budget is None:
            for key in ("rev", "kwh", "oil"):
                fallback = metrics.get(key)
                if fallback and fallback.get("budget_pct") is not None:
                    budget = fallback["budget_pct"]
                    break
        return tr(
            "amoeba.insights.lead.profit",
            locale,
            value=_fmt(profit["dims"].get(dim)),
            trend=_fmt(trend) if trend is not None else "-",
            budget=_fmt(budget) if budget is not None else "-",
        )
    if revenue and revenue.get("dims", {}).get(dim) is not None:
        trend = revenue.get("delta_pct")
        return tr(
            "amoeba.insights.lead.revenue",
            locale,
            value=_fmt(revenue["dims"].get(dim)),
            trend=_fmt(trend) if trend is not None else "-",
        )
    if items:
        return items[0].get("evidence") or items[0].get("title") or ""
    return tr("amoeba.insights.lead.empty", locale)


def _summary_prompt(overview: dict[str, Any], *, locale: str, org_name: str) -> str:
    lines: list[str] = [f"org: {org_name}", f"dim: {overview.get('dim')}", "metrics:"]
    for _key, card in overview.get("metrics", {}).items():
        if card.get("category") == "hidden":
            continue
        name = _metric_name(card, locale)
        value = card.get("dims", {}).get(overview.get("dim", "d"))
        parts = [f"{name}={_fmt(value)}{card.get('unit') or ''}"]
        if card.get("delta_pct") is not None:
            parts.append(f"delta={_fmt(card['delta_pct'])}%")
        if card.get("budget_pct") is not None:
            parts.append(f"budget={_fmt(card['budget_pct'])}%")
        lines.append(f"- {' '.join(parts)}")
    return "\n".join(lines)


def _parse_items(text: str) -> list[dict[str, Any]]:
    """Accept a JSON array of {level, title, evidence, action} objects."""
    raw = strip_thinking(text or "").strip()
    start = raw.find("[")
    end = raw.rfind("]")
    if start < 0 or end <= start:
        return []
    try:
        data = json.loads(raw[start : end + 1])
    except json.JSONDecodeError:
        return []
    items: list[dict[str, Any]] = []
    if not isinstance(data, list):
        return []
    for row in data:
        if not isinstance(row, dict):
            continue
        level = str(row.get("level", "info"))
        if level not in LEVELS:
            level = "info"
        title = str(row.get("title", "")).strip()[:_MAX_LINE_LEN]
        evidence = str(row.get("evidence", "")).strip()[: _MAX_LINE_LEN * 2]
        action = str(row.get("action", "")).strip()[:_MAX_LINE_LEN]
        if title:
            items.append(
                {
                    "level": level,
                    "title": title,
                    "evidence": evidence,
                    "action": action,
                    "source": "llm",
                }
            )
    return items[:_MAX_ITEMS]


async def build_insights(
    *,
    overview: dict[str, Any],
    locale: str,
    org_name: str,
    models: Any | None,
) -> dict[str, Any]:
    """LLM narrative with a rule-based fallback; returns {lead, items}."""
    fallback = rule_insights(overview, locale=locale, org_name=org_name)
    result = {"lead": lead_line(overview, fallback, locale=locale), "items": fallback}
    if models is None:
        return result
    try:
        access = models.get(None)
        system = tr("amoeba.insights.system", locale)
        user = _summary_prompt(overview, locale=locale, org_name=org_name)
        raw = await asyncio.wait_for(
            access.ainvoke_text(user, system=system, timeout_s=_LLM_TIMEOUT_SECONDS),
            timeout=_LLM_TIMEOUT_SECONDS,
        )
        items = _parse_items(raw or "")
        if items:
            items.sort(key=lambda i: _LEVEL_ORDER.get(i["level"], 99))
            result["items"] = items
        return result
    except Exception:
        logger.info("amoeba LLM summary failed; using rule fallback", exc_info=True)
        return result


__all__ = ["build_insights", "lead_line", "rule_insights"]
